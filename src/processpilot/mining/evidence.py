"""Evidence store: the contract between deterministic mining and the LLM.

WHY this module is the keystone of the whole design: the LLM never sees an event
log, only ``EvidenceItem``s. Each item has a deterministic ID (type prefix +
rank + segment slug) so that two runs over the same data produce citable,
comparable IDs, and so that an agent claim citing an ID can be mechanically
verified. Any claim citing an unknown ID is rejected and the node retried.

The ``summary`` sentence is generated by *code*, not by a model, so that the
human-readable description of a finding cannot drift from its metrics.

Persisted as JSON next to the run's other artefacts; the query methods on
``EvidenceStore`` are what ``agent/tools.py`` wraps as read-only tools.

ID scheme: ``<PREFIX>-<rank:02d>-<segment-slug>``; conformance items use the
rule id instead of a rank (``CF-R-02-<slug>``) so a rule keeps its ID when
other rules are added. Prefixes: BN bottleneck, AW wait before an activity,
VA variant, RW rework, RS resource workload, HO handover, CF conformance rule,
CM conformance to the reference model (``CM-00`` = overall result or "not
performed", ``CM-01..`` = ranked deviations), KPI segment KPIs.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel

from processpilot.mining.activities import ActivityWait
from processpilot.mining.bottlenecks import Bottleneck
from processpilot.mining.conformance import ConformanceResult
from processpilot.mining.kpis import SegmentKPIs
from processpilot.mining.reference import ReferenceConformance
from processpilot.mining.resources import ResourceAnalysis
from processpilot.mining.rework import ReworkItem
from processpilot.mining.variants import VariantSummary

EvidenceType = Literal[
    "bottleneck", "activity", "variant", "rework", "resource", "conformance", "kpi"
]

_SECONDS_PER_MINUTE = 60
_SECONDS_PER_HOUR = 3600
_SECONDS_PER_DAY = 86400


class EvidenceItem(BaseModel):
    """One citable finding. Metrics are the numbers; summary restates them."""

    id: str
    segment: str
    type: EvidenceType
    summary: str
    metrics: dict[str, Any]
    refs: list[str] = []


class EvidenceStore(BaseModel):
    """All evidence of a run, with the read-only queries the agent tools wrap."""

    items: list[EvidenceItem] = []

    def get(self, evidence_id: str) -> EvidenceItem:
        """The item with ``evidence_id``; ``KeyError`` if it does not exist."""
        for item in self.items:
            if item.id == evidence_id:
                return item
        raise KeyError(f"unknown evidence id: {evidence_id}")

    def ids(self) -> list[str]:
        """Every evidence id, in store order."""
        return [item.id for item in self.items]

    def segments(self) -> list[str]:
        """Distinct segments, in store order."""
        return list(dict.fromkeys(item.segment for item in self.items))

    def query(
        self, segment: str | None = None, type: EvidenceType | None = None
    ) -> list[EvidenceItem]:
        """Items filtered by segment and/or type, in store (= rank) order."""
        return [
            i
            for i in self.items
            if (segment is None or i.segment == segment) and (type is None or i.type == type)
        ]

    def unknown_ids(self, cited: list[str]) -> list[str]:
        """Cited ids that do not exist -- the check behind rejecting agent output."""
        known = set(self.ids())
        return [c for c in cited if c not in known]

    def merged(self, other: EvidenceStore) -> EvidenceStore:
        """A new store with ``other``'s items appended; ids must stay unique."""
        clash = set(self.ids()) & set(other.ids())
        if clash:
            raise ValueError(f"duplicate evidence ids: {sorted(clash)}")
        return EvidenceStore(items=[*self.items, *other.items])

    def to_json(self, path: Path) -> None:
        """Write the store as indented JSON (deterministic for identical input)."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.model_dump_json(indent=2), encoding="utf-8")

    @classmethod
    def from_json(cls, path: Path) -> EvidenceStore:
        """Load a store written by ``to_json``."""
        return cls.model_validate(json.loads(Path(path).read_text(encoding="utf-8")))


def segment_slug(segment: str) -> str:
    """``"3-way match, invoice before GR"`` -> ``"3-way-match-invoice-before-gr"``."""
    slug = re.sub(r"[^a-z0-9]+", "-", segment.lower()).strip("-")
    if not slug:
        raise ValueError(f"segment name {segment!r} has no characters usable in an id")
    return slug


def format_duration(seconds: float | None) -> str:
    """Human-readable duration for summaries; the exact seconds stay in metrics."""
    if seconds is None:
        return "n/a"
    sign = "-" if seconds < 0 else ""
    s = abs(seconds)
    if s >= _SECONDS_PER_DAY:
        return f"{sign}{s / _SECONDS_PER_DAY:.1f} days"
    if s >= _SECONDS_PER_HOUR:
        return f"{sign}{s / _SECONDS_PER_HOUR:.1f} h"
    if s >= _SECONDS_PER_MINUTE:
        return f"{sign}{s / _SECONDS_PER_MINUTE:.0f} min"
    return f"{sign}{s:.0f} s"


def _pct(share: float | None) -> str:
    return "n/a" if share is None else f"{share * 100:.1f}%"


def build_segment_evidence(
    segment: str,
    kpis: SegmentKPIs,
    bottlenecks: list[Bottleneck],
    variants: VariantSummary,
    rework: list[ReworkItem],
    resources: ResourceAnalysis,
    conformance: list[ConformanceResult],
    activity_waits: list[ActivityWait],
    reference: ReferenceConformance,
) -> EvidenceStore:
    """Turn one segment's mining results into evidence items (pure)."""
    slug = segment_slug(segment)
    kpi_id = f"KPI-01-{slug}"
    bn_ids = {(b.edge.source, b.edge.target): f"BN-{b.rank:02d}-{slug}" for b in bottlenecks}
    items: list[EvidenceItem] = [
        EvidenceItem(
            id=kpi_id,
            segment=segment,
            type="kpi",
            summary=(
                f"Segment '{segment}' has {kpis.case_count:,} cases and {kpis.event_count:,} "
                f"events ({kpis.collapsed_event_count:,} same-instant repeats collapsed); "
                f"median case throughput is {format_duration(kpis.median_throughput_seconds)} "
                f"(mean {format_duration(kpis.mean_throughput_seconds)}, "
                f"P90 {format_duration(kpis.p90_throughput_seconds)})." + _filter_note(kpis)
            ),
            metrics=kpis.model_dump(),
        )
    ]

    for b in bottlenecks:
        e = b.edge
        items.append(
            EvidenceItem(
                id=bn_ids[(e.source, e.target)],
                segment=segment,
                type="bottleneck",
                summary=(
                    f"Transition '{e.source}' -> '{e.target}' occurs in {_pct(e.case_share)} of "
                    f"cases ({e.case_count:,}) with a median wait of "
                    f"{format_duration(e.median_wait_seconds)} (mean "
                    f"{format_duration(e.mean_wait_seconds)}, P90 "
                    f"{format_duration(e.p90_wait_seconds)}); impact rank {b.rank}."
                ),
                metrics={**e.model_dump(), "impact_score": b.impact_score, "rank": b.rank},
                refs=["dfg.json", kpi_id],
            )
        )

    for w in activity_waits:
        into = [bn_id for (_, target), bn_id in bn_ids.items() if target == w.activity]
        items.append(
            EvidenceItem(
                id=f"AW-{w.rank:02d}-{slug}",
                segment=segment,
                type="activity",
                summary=(
                    f"Cases wait a median {format_duration(w.median_wait_seconds)} before "
                    f"'{w.activity}' (time since the previous event; mean "
                    f"{format_duration(w.mean_wait_seconds)}, P90 "
                    f"{format_duration(w.p90_wait_seconds)}) over {w.occurrences:,} occurrences "
                    f"in {_pct(w.case_share)} of cases; most often preceded by "
                    f"'{w.top_predecessor}' ({_pct(w.top_predecessor_share)} of occurrences); "
                    f"activity-wait rank {w.rank}."
                ),
                metrics=w.model_dump(),
                refs=["activity_waits.json", kpi_id, *into],
            )
        )

    for v in variants.variants:
        label = (
            "the happy path (most frequent, not necessarily best)"
            if v.is_happy_path
            else f"variant rank {v.rank}"
        )
        items.append(
            EvidenceItem(
                id=f"VA-{v.rank:02d}-{slug}",
                segment=segment,
                type="variant",
                summary=(
                    f"A {len(v.activities)}-step path followed by {_pct(v.case_share)} of cases "
                    f"({v.case_count:,}) is {label}; its median throughput is "
                    f"{format_duration(v.median_throughput_seconds)}. The top "
                    f"{len(variants.variants)} of {variants.variant_count:,} variants together "
                    f"cover {_pct(variants.top_n_case_share)} of cases."
                ),
                metrics={
                    **v.model_dump(),
                    "variant_count": variants.variant_count,
                    "top_n_case_share": variants.top_n_case_share,
                },
                refs=[kpi_id],
            )
        )

    for r in rework:
        loop_ref = bn_ids.get((r.activity, r.activity))
        items.append(
            EvidenceItem(
                id=f"RW-{r.rank:02d}-{slug}",
                segment=segment,
                type="rework",
                summary=(
                    f"'{r.activity}' is repeated within {_pct(r.case_share)} of cases "
                    f"({r.case_count:,}; {r.extra_occurrences:,} extra executions); those cases "
                    f"take a median {format_duration(r.extra_median_throughput_seconds)} longer "
                    "than cases performing it once (association, not proven cause)."
                ),
                metrics=r.model_dump(),
                refs=[kpi_id, *([loop_ref] if loop_ref else [])],
            )
        )

    items.extend(_resource_evidence(segment, slug, resources, bn_ids))

    for c in conformance:
        items.append(
            EvidenceItem(
                id=f"CF-{c.rule_id}-{slug}",
                segment=segment,
                type="conformance",
                summary=_conformance_summary(c),
                metrics=c.model_dump(),
            )
        )
    items.extend(_reference_evidence(segment, slug, reference))
    return EvidenceStore(items=items)


def _filter_note(kpis: SegmentKPIs) -> str:
    f = kpis.variant_filter
    if f is None:
        return ""
    scope = (
        "every number in this segment"
        if f.apply_to == "all"
        else "the as-is model only (all other numbers use every case)"
    )
    return (
        f" A variant filter ({f.mode} {f.value:g}) kept {f.variant_count_after:,} of "
        f"{f.variant_count_before:,} variants, covering {_pct(f.kept_case_share)} of cases; "
        f"it applies to {scope}."
    )


def _reference_evidence(segment: str, slug: str, ref: ReferenceConformance) -> list[EvidenceItem]:
    overall_id = f"CM-00-{slug}"
    if not ref.available:
        return [
            EvidenceItem(
                id=overall_id,
                segment=segment,
                type="conformance",
                summary=(
                    "Conformance against a reference process model was not performed: "
                    f"{ref.skipped_reason}. Absence of model deviations is NOT evidence that "
                    "the segment follows its intended process."
                ),
                metrics={"available": False, "skipped_reason": ref.skipped_reason},
            )
        ]
    completed = (
        "no case-completion definition is configured"
        if ref.completed_evaluated_cases is None
        else (
            f"{ref.completed_conforming_cases:,} of {ref.completed_evaluated_cases:,} "
            f"({_pct(ref.completed_conforming_share)})"
        )
    )
    unmodelled = (
        f" {len(ref.unmodelled_activities)} observed activities are not in the model "
        f"({ref.cases_with_unmodelled_activities:,} cases)."
        if ref.unmodelled_activities
        else ""
    )
    unobserved = (
        f" {len(ref.unobserved_model_activities)} model activities never occur."
        if ref.unobserved_model_activities
        else ""
    )
    items = [
        EvidenceItem(
            id=overall_id,
            segment=segment,
            type="conformance",
            summary=(
                f"Against reference model '{ref.model_name}' ({ref.method}), "
                f"{ref.conforming_cases:,} of {ref.evaluated_cases:,} cases "
                f"({_pct(ref.conforming_share)}) conform; among completed cases: {completed}. "
                f"Replay fitness is {ref.replay_fitness:.3f}; "
                f"{ref.cases_unfit_without_flagged_activity:,} non-conforming cases only stop "
                f"before the model's end (often still running).{unmodelled}{unobserved}"
            ),
            metrics=ref.model_dump(exclude={"deviations"}),
        )
    ]
    for d in ref.deviations:
        what = (
            "is executed where the reference model does not allow it"
            if d.kind == "executed_when_not_allowed"
            else "occurs but is not part of the reference model"
        )
        items.append(
            EvidenceItem(
                id=f"CM-{d.rank:02d}-{slug}",
                segment=segment,
                type="conformance",
                summary=(
                    f"'{d.activity}' {what} in {_pct(d.case_share)} of cases "
                    f"({d.case_count:,}); model-deviation rank {d.rank}."
                ),
                metrics={**d.model_dump(), "model_name": ref.model_name},
                refs=[overall_id],
            )
        )
    return items


def _resource_evidence(
    segment: str, slug: str, res: ResourceAnalysis, bn_ids: dict[tuple[str, str], str]
) -> list[EvidenceItem]:
    if not res.available:
        return [
            EvidenceItem(
                id=f"RS-00-{slug}",
                segment=segment,
                type="resource",
                summary=(
                    f"Resource analysis was not performed: {res.skipped_reason}. Absence of "
                    "resource findings is NOT evidence that no resource problem exists."
                ),
                metrics={"available": False, "skipped_reason": res.skipped_reason},
            )
        ]
    items = [
        EvidenceItem(
            id=f"HO-00-{slug}",
            segment=segment,
            type="resource",
            summary=(
                "Across all transitions, the median wait is "
                f"{format_duration(res.median_handover_wait_seconds)} when the resource changes "
                f"and {format_duration(res.median_same_resource_wait_seconds)} when it does not "
                f"({res.unassigned_event_count:,} events have no resource)."
            ),
            metrics={
                "available": True,
                "median_handover_wait_seconds": res.median_handover_wait_seconds,
                "median_same_resource_wait_seconds": res.median_same_resource_wait_seconds,
                "unassigned_event_count": res.unassigned_event_count,
            },
        )
    ]
    for w in res.workload:
        items.append(
            EvidenceItem(
                id=f"RS-{w.rank:02d}-{slug}",
                segment=segment,
                type="resource",
                summary=(
                    f"Resource '{w.resource}' records {_pct(w.event_share)} of events "
                    f"({w.event_count:,}) across {w.case_count:,} cases and "
                    f"{w.distinct_activities} distinct activities; workload rank {w.rank}."
                ),
                metrics=w.model_dump(),
            )
        )
    for h in res.handovers:
        bn_ref = bn_ids.get((h.source, h.target))
        items.append(
            EvidenceItem(
                id=f"HO-{h.rank:02d}-{slug}",
                segment=segment,
                type="resource",
                summary=(
                    f"On '{h.source}' -> '{h.target}', {_pct(h.handover_share_of_transitions)} of "
                    f"transitions hand over to a different resource ({_pct(h.handover_case_share)}"
                    f" of cases); median wait {format_duration(h.median_handover_wait_seconds)} "
                    f"with handover vs {format_duration(h.median_same_resource_wait_seconds)} "
                    f"without; handover impact rank {h.rank}."
                ),
                metrics=h.model_dump(),
                refs=[bn_ref] if bn_ref else [],
            )
        )
    return items


def _conformance_summary(c: ConformanceResult) -> str:
    if c.activities_missing_from_segment:
        missing = ", ".join(c.activities_missing_from_segment)
        outcome = (
            "so it could not be evaluated on any case"
            if c.evaluated_cases == 0
            else f"so its {c.violation_count:,} violations reflect rule scope, not the process"
        )
        return (
            f"Rule {c.rule_id} ({c.rule_name}) names activities never observed in this segment "
            f"({missing}), {outcome}; the rule is likely misconfigured for this segment."
        )
    completed = (
        "no case-completion definition is configured"
        if c.completed_evaluated_cases is None
        else (
            f"{c.completed_violation_count:,} of {c.completed_evaluated_cases:,} "
            f"({_pct(c.completed_violation_share)})"
        )
    )
    tied = f"; {c.tied_cases:,} case(s) tie on timestamp (order unknown)" if c.tied_cases else ""
    return (
        f"Rule {c.rule_id} ({c.rule_name}) is violated in {c.violation_count:,} of "
        f"{c.evaluated_cases:,} evaluated cases ({_pct(c.violation_share)}); among completed "
        f"cases: {completed}{tied}."
    )
